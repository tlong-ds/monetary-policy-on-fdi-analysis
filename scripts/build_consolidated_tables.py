def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    print("Generating consolidated LaTeX tables...")

    write_tex("tab_main_and_diagnostics.tex", generate_main_table())
    write_tex("tab_appendix_descriptive.tex", generate_appendix_table())

    # Remove old individual tables (keep as cleanup note)
    print("\nDone. Now updating methodology_results_interpretation.tex")

if __name__ == "__main__":
    main()
